import { readFileSync } from 'node:fs';
import { expect, test } from '@playwright/test';

test.use({ trace: 'off', video: 'off', screenshot: 'off' });
test('real isolated API: owner edits and rejects stale suggestion; viewer reads but cannot write', async ({ browser, baseURL }) => {
  const fixturePath = process.env.YANCE_ROLES_FIXTURE;
  test.skip(!fixturePath, 'Requires isolated role fixture; never a production target');
  expect(new URL(baseURL!).hostname).toMatch(/^(127\.0\.0\.1|localhost)$/);
  const fixture = JSON.parse(readFileSync(fixturePath!, 'utf8')) as { token: string; viewer_token: string; application_id: string };
  const owner = await browser.newContext({ baseURL });
  await owner.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await owner.addInitScript(token => localStorage.setItem('yance_token', token), fixture.token);
  const page = await owner.newPage();
  await page.goto(`/applications/${fixture.application_id}`);
  await page.getByRole('tab', { name: /^工作稿/ }).click();
  await page.getByRole('button', { name: '重新生成', exact: true }).click();
  await expect(page.getByText(/v1 · deterministic-evidence-v1/)).toBeVisible();
  await page.getByRole('textbox', { name: '人工编辑摘要' }).fill('合成联调修改后的摘要');
  await page.getByRole('button', { name: '保存为新版本', exact: true }).click();
  await expect(page.getByText(/v2 · deterministic-evidence-v1/)).toBeVisible();
  await page.getByRole('tab', { name: /^动态/ }).click();
  const selector = page.getByRole('combobox', { name: '评论关联版本' });
  const option = await selector.locator('option').filter({ hasText: '工作稿 v1' }).getAttribute('value');
  await selector.selectOption(option!);
  await page.getByRole('textbox', { name: '建议替换摘要（可选）' }).fill('针对旧稿的合成建议');
  await page.getByRole('textbox', { name: '添加协作评论' }).fill('旧稿建议保持版本关联');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await expect(page.getByText('工作区成员 · 工作稿 v1', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: '接受摘要建议', exact: true }).click();
  await expect(page.getByText(/Suggestion version or sources changed/)).toBeVisible();
  await page.getByRole('button', { name: '拒绝建议', exact: true }).click();
  await expect(page.getByText('已拒绝', { exact: true })).toBeVisible();
  await owner.close();

  const reader = await browser.newContext({ baseURL });
  await reader.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await reader.addInitScript(token => localStorage.setItem('yance_token', token), fixture.viewer_token);
  const view = await reader.newPage();
  await view.goto(`/applications/${fixture.application_id}`);
  await expect(view.getByText(/当前为只读成员/)).toBeVisible();
  await expect(view.getByRole('button', { name: '创建补证待办', exact: true })).toBeDisabled();
  await view.getByRole('tab', { name: /^工作稿/ }).click();
  await expect(view.getByRole('button', { name: '重新生成', exact: true })).toBeDisabled();
  await expect(view.getByRole('button', { name: '保存为新版本', exact: true })).toBeDisabled();
  await expect(view.getByRole('button', { name: '批准工作稿', exact: true })).toBeDisabled();
  await expect(view.getByRole('combobox', { name: '对比基准版本', exact: false })).toBeEnabled();
  await view.getByRole('tab', { name: /^动态/ }).click();
  await expect(view.getByRole('textbox', { name: '添加协作评论' })).toBeDisabled();
  await expect(view.getByRole('button', { name: '发送', exact: true })).toBeDisabled();
  const denied = await reader.request.post(`/api/v1/applications/${fixture.application_id}/comments`, { headers: { Authorization: `Bearer ${fixture.viewer_token}` }, data: { body: '合成绕过界面尝试' } });
  expect(denied.status()).toBe(403);
  const detail = await reader.request.get(`/api/v1/applications/${fixture.application_id}`, { headers: { Authorization: `Bearer ${fixture.viewer_token}` } });
  expect(detail.status()).toBe(200);
  const data = await detail.json();
  expect(data.generated).toHaveLength(2);
  expect(data.comments).toHaveLength(1);
  expect(data.comments[0].resolution.decision).toBe('reject');
  await reader.close();
});
